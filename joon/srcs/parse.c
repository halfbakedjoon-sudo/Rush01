int	parse(int argc, char **argv, int clues[16])
{
	int	i;
	int	j;

	if (argc != 2)
		return (1);
	i = 0;
	j = 0;
	while (argv[1][i])
	{
		if (argv[1][i] >= '1' && argv[1][i] <= '5')
		{
			clues[j] = argv[1][i] - '0';
			j++;
		}
		i++;
	}
	if (j != 16)
	{
		return (1);
	}
	return (0);
}
