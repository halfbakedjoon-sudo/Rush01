int	check(char **input)
{
	int	n;

	n = 0;
	while (input[1][n])
	{
		if (n % 2 == 0 && !(input[1][n] >= '0' && input[1][n] <= '9'))
		{
			return (1);
		}
		if (n % 2 == 1 && input[1][n] != ' ')
		{
			return (2);
		}
		n++;
	}
	return (0);
}
